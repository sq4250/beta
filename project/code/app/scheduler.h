/**
 * scheduler.h - 时间片任务调度器
 *
 * 基于 tick 的时间片轮转调度器。
 * scheduler_update() 在 ISR 中运行 (仅做计数)，
 * scheduler_run() 在主循环中运行 (消费 pending 执行任务)。
 */

#ifndef SCHEDULER_H
#define SCHEDULER_H

#include "common.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     调度器初始化
// 参数说明     void
// 返回参数     void
// 使用示例     scheduler_init();
// 备注信息     初始化 tick 硬件和任务表，在 clock_init() 之后调用
//-------------------------------------------------------------------------------------------------------------------
void scheduler_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     调度器运行 (主循环调用)
// 参数说明     void
// 返回参数     void
// 使用示例     while(1) { scheduler_run(); }
// 备注信息     遍历任务表，消费 pending 计数，执行到期任务。无任务时快速返回。
//-------------------------------------------------------------------------------------------------------------------
void scheduler_run(void);

#endif
