/**
 * longitudinal.h — 纵向 LADRC (LESO + PD) + 差速分配
 *
 * 模型: alpha*v + v_dot = b0 * throttle + f
 * LESO: 降阶观测器从 v 估计总扰动 f̂
 * 控制: thr = (kp*e_x + kd*(v_ref-v) + a_ref + alpha*v - f̂) / b0
 * 差速: thr_L/R = thr_avg * (R ± w/2) / R
 */

#ifndef LONGITUDINAL_H
#define LONGITUDINAL_H

#include "common.h"
#include "config.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     纵向控制器初始化
// 参数说明     void
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void longitudinal_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     纵向 LADRC 单步 (200Hz)
// 参数说明     v_meas      实测速度 [m/s] (左右编码器平均)
// 参数说明     v_ref       参考速度 [m/s]
// 参数说明     a_ref       前馈加速度 [m/s²] (NN输出)
// 参数说明     e_x         纵向位置偏差 [m] (切线投影)
// 参数说明     delta       当前前轮转角 [rad] (差速用)
// 参数说明     thr_L       输出: 左轮油门 [-1,1]
// 参数说明     thr_R       输出: 右轮油门 [-1,1]
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void longitudinal_step(f32 *thr_L, f32 *thr_R,
                       f32 v_meas, f32 v_ref, f32 a_ref, f32 e_x, f32 delta);

#endif
