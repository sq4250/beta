static inline void dense_linear(f32 *out, const f32 *inp, const f32 *w, const f32 *b,
                                int in_dim, int out_dim) {
    for (int i = 0; i < out_dim; i++) {
        f32 s = b[i];
        for (int j = 0; j < in_dim; j++) s += w[i*in_dim + j] * inp[j];
        out[i] = s;
    }
}

static inline void dense_relu(f32 *out, const f32 *inp, const f32 *w, const f32 *b,
                              int in_dim, int out_dim) {
    for (int i = 0; i < out_dim; i++) {
        f32 s = b[i];
        for (int j = 0; j < in_dim; j++) s += w[i*in_dim + j] * inp[j];
        out[i] = (s > 0.0f) ? s : 0.0f;
    }
}

static void polar_encode(f32 out[10], const car_state_t *s,
                         const waypoint_t *g1, const waypoint_t *g2, const waypoint_t *g3) {
    f32 dx1 = g1->x - s->x, dy1 = g1->y - s->y;
    out[0] = s->v / NN_V_SCALE;
    out[1] = s->delta / DELTA_MAX;
    out[2] = sqrtf(dx1*dx1 + dy1*dy1) / NN_D_SCALE;
    out[3] = wrap_pi(atan2f(dy1, dx1) - s->theta) / NN_A_SCALE;

    if (out[8] > 0.0f) {
        f32 dx12 = g2->x - g1->x, dy12 = g2->y - g1->y;
        out[4] = sqrtf(dx12*dx12 + dy12*dy12) / NN_D_SCALE;
        out[5] = wrap_pi(atan2f(dy12, dx12) - atan2f(dy1, dx1)) / NN_A_SCALE;
    } else { out[4] = 0.0f; out[5] = 0.0f; }

    if (out[9] > 0.0f) {
        f32 dx23 = g3->x - g2->x, dy23 = g3->y - g2->y;
        out[6] = sqrtf(dx23*dx23 + dy23*dy23) / NN_D_SCALE;
        out[7] = wrap_pi(atan2f(dy23, dx23) - atan2f(g2->y - g1->y, g2->x - g1->x)) / NN_A_SCALE;
    } else { out[6] = 0.0f; out[7] = 0.0f; }
}

static void nn_forward(f32 out[2], const f32 inp[10]) {
    f32 h_state[NN_H_STATE]; dense_linear(h_state, inp, fc_state_w, fc_state_b, 2, NN_H_STATE);
    f32 h_t1[NN_H_TGT];     dense_linear(h_t1, inp+2, fc_tgt_w, fc_tgt_b, 2, NN_H_TGT);
    f32 h_t2[NN_H_TGT];     dense_linear(h_t2, inp+4, fc_tgt_w, fc_tgt_b, 2, NN_H_TGT);
    f32 h_t3[NN_H_TGT];     dense_linear(h_t3, inp+6, fc_tgt_w, fc_tgt_b, 2, NN_H_TGT);
    for (int i = 0; i < NN_H_TGT; i++) { h_t2[i] *= inp[8]; h_t3[i] *= inp[9]; }
    f32 cat[32];
    for (int i = 0; i < NN_H_STATE; i++) cat[i] = h_state[i];
    for (int i = 0; i < NN_H_TGT;   i++) cat[NN_H_STATE + i]      = h_t1[i];
    for (int i = 0; i < NN_H_TGT;   i++) cat[NN_H_STATE + 8 + i]  = h_t2[i];
    for (int i = 0; i < NN_H_TGT;   i++) cat[NN_H_STATE + 16 + i] = h_t3[i];
    f32 h1[NN_H1]; dense_relu(h1, cat, fc1_w, fc1_b, 32, NN_H1);
    f32 h2[NN_H2]; dense_relu(h2, h1,  fc2_w, fc2_b, NN_H1, NN_H2);
    f32 h3[NN_H3]; dense_relu(h3, h2,  fc3_w, fc3_b, NN_H2, NN_H3);
    dense_linear(out, h3, fc4_w, fc4_b, NN_H3, 2);
    if (out[0] >  NN_A_MAX)       out[0] =  NN_A_MAX;
    if (out[0] < -NN_A_BRAKE_MAX) out[0] = -NN_A_BRAKE_MAX;
    if (out[1] >  NN_O_MAX)       out[1] =  NN_O_MAX;
    if (out[1] < -NN_O_MAX)       out[1] = -NN_O_MAX;
}

void nn_planner_step_d5v15(f32 out[2], const car_state_t *vst,
                     const waypoint_t *g1, const waypoint_t *g2, const waypoint_t *g3,
                     f32 v2, f32 v3) {
    f32 inp[10]; inp[8] = v2; inp[9] = v3;
    polar_encode(inp, vst, g1, g2, g3);
    nn_forward(out, inp);
}

