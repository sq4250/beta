/**
 * tracker.h — LQR 横向跟踪器 (200Hz)
 *
 * 控制律: omega_cmd = omega_ff - (g1*ey + g2*ey_dot + g3*eth + g4*eth_dot + g5*ed)
 * 纵向:   LADRC 位置闭环 (与 tracking_layer_step 配合)
 */

#ifndef TRACKER_H
#define TRACKER_H

#include "car_state.h"
#include "config.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     跟踪器初始化
// 参数说明     void
// 返回参数     void
// 使用示例     tracker_init();
//-------------------------------------------------------------------------------------------------------------------
void tracker_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     LQR 增益查表 (线性插值)
// 参数说明     v           当前速度 [m/s]
// 参数说明     g           输出 [g1,g2,g3,g4,g5]
// 返回参数     void
//-------------------------------------------------------------------------------------------------------------------
void tracker_lqr_gains(f32 g[5], f32 v);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     跟踪器单步 (200Hz, ISR上下文, 与PWM同步)
// 参数说明     rs          真实车状态 (输入/输出)
// 参数说明     vst         虚拟车状态 (参考)
// 参数说明     omega_ff    NN前馈转向角速度 [rad/s]
// 返回参数     omega_cmd   转向角速度指令 [rad/s]
// 使用示例     f32 omg = tracker_step(&real, &virt, nn_omega);
// 备注信息     计算5项误差, LQR反馈, 切线投影消e_x
//-------------------------------------------------------------------------------------------------------------------
f32 tracker_step(CarState *rs, const CarState *vst, f32 omega_ff);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前横向/纵向误差 (用于遥测+纵向控制)
// 参数说明     void
// 返回参数     f32         误差 [m]
//-------------------------------------------------------------------------------------------------------------------
f32 tracker_get_ey(void);
f32 tracker_get_ex(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前转向指令 (用于遥测)
// 参数说明     void
// 返回参数     f32         omega_cmd [rad/s]
//-------------------------------------------------------------------------------------------------------------------
f32 tracker_get_omega_cmd(void);

#endif
