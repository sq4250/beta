/**
 * hal_tick.c - 系统 tick 硬件抽象层实现
 *
 * 基于 zf_driver PIT_CH1 产生 1ms 周期中断，
 * 在 ISR 中递增 tick_ms 并调用注册的回调函数。
 */

#include "zf_common_headfile.h"
#include "hal_tick.h"

static u32 tick_ms = 0;                                                         // 系统 tick 计数 (ms)
static void (*tick_handler)(void);                                              // tick 回调函数指针
static u8 is_init = 0;                                                          // 初始化标志

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     tick 中断回调
// 参数说明     void
// 返回参数     void
// 使用示例     在 pit0_ch1_isr 中调用 hal_tick_callback()
// 备注信息     tick_ms 自增后调用用户注册的回调函数
//-------------------------------------------------------------------------------------------------------------------
void hal_tick_callback(void) {
    tick_ms++;
    if (tick_handler) {
        tick_handler();
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     系统 tick 初始化
// 参数说明     handler     每 tick 回调函数 (ISR 上下文执行)
// 返回参数     void
// 使用示例     hal_tick_init(scheduler_update);
// 备注信息     使用 PIT_CH1 产生 1kHz 定时中断，作为系统心跳
//-------------------------------------------------------------------------------------------------------------------
void hal_tick_init(void (*handler)(void)) {
    if (is_init) return;
    is_init = 1;

    tick_handler = handler;
    pit_ms_init(PIT_CH1, 1);                                                    // PIT_CH1 1ms 周期中断
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取系统 tick 计数
// 参数说明     void
// 返回参数     u32          系统启动以来的 tick 数 (单位: ms)
// 使用示例     u32 now = hal_tick_get();
// 备注信息     在 ISR 中递增，主循环可安全读取
//-------------------------------------------------------------------------------------------------------------------
u32 hal_tick_get(void) {
    return tick_ms;
}
