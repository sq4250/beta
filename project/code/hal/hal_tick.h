/**
 * hal_tick.h - 系统 tick 硬件抽象层
 *
 * 使用 PIT_CH1 产生 1kHz 定时中断，作为调度器心跳。
 */

#ifndef HAL_TICK_H
#define HAL_TICK_H

#include "common.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     系统 tick 初始化
// 参数说明     handler     每 tick 回调函数 (ISR 上下文执行，需短小)
// 返回参数     void
// 使用示例     hal_tick_init(scheduler_update);
// 备注信息     使用 PIT_CH1 产生 1kHz 定时中断，作为系统心跳
//-------------------------------------------------------------------------------------------------------------------
void hal_tick_init(void (*handler)(void));

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取系统 tick 计数
// 参数说明     void
// 返回参数     u32          系统启动以来的 tick 数 (单位: ms)
// 使用示例     u32 now = hal_tick_get();
// 备注信息     在 ISR 中递增，主循环可安全读取
//-------------------------------------------------------------------------------------------------------------------
u32 hal_tick_get(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     tick 中断回调 (由 PIT ISR 调用)
// 参数说明     void
// 返回参数     void
// 使用示例     在 pit0_ch1_isr 中调用 hal_tick_callback()
// 备注信息     内部使用，用户无需关心
//-------------------------------------------------------------------------------------------------------------------
void hal_tick_callback(void);

#endif
