"""汇总所有趟次航点通过精度"""
import numpy as np

WP = np.array([[2,0],[2,2],[0,2],[0,0]])

def calc_min_d(cx, cy):
    result = []
    for wp in WP:
        md = float('inf')
        for j in range(len(cx)):
            d = np.sqrt((cx[j]-wp[0])**2 + (cy[j]-wp[1])**2)
            if d < md: md = d
        for j in range(len(cx)-1):
            for k in range(10):
                a = k/10.
                x = cx[j]+a*(cx[j+1]-cx[j])
                y = cy[j]+a*(cy[j+1]-cy[j])
                d = np.sqrt((x-wp[0])**2 + (y-wp[1])**2)
                if d < md: md = d
        result.append(md*100)
    return result

def parse_xy(raw):
    lines = [l.strip().split(',') for l in raw.strip().split('\n')]
    data = np.array([[float(x) for x in l] for l in lines])
    return data[:,1], data[:,2]

def parse_ey(raw):
    lines = [l.strip().split(',') for l in raw.strip().split('\n')]
    data = np.array([[float(x) for x in l] for l in lines])
    return data[:,5] if data.shape[1] > 5 else None

